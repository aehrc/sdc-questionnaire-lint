// Regenerates src/analysis/fhirpath-function-catalog.ts from the installed fhirpath.js. Run it
// after bumping fhirpath; test/analysis/fhirpath-function-catalog.test.ts fails until you do:
//   npm run generate:functions --workspace @aehrc/sdc-questionnaire-lint
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

export const catalogModule = fileURLToPath(
  new URL('../src/analysis/fhirpath-function-catalog.ts', import.meta.url),
);

// The version and the main source file of the installed fhirpath.js, which holds the table.
export function installedFhirPath(): { version: string; source: string } {
  const require = createRequire(import.meta.url);
  const { version } = require('fhirpath/package.json') as { version: string };
  return { version, source: readFileSync(require.resolve('fhirpath'), 'utf8') };
}

// fhirpath.js does not export engine.invocationTable, so its keys are read from the source text.
// Top-level keys are indented by two spaces and are either bare identifiers or quoted operators;
// continuation lines are indented deeper.
export function invocationTableKeys(source: string): string[] {
  const body = /^engine\.invocationTable = \{\n([\s\S]*?)\n\};$/m.exec(source)?.[1];
  if (body === undefined) throw new Error('engine.invocationTable not found in fhirpath.js');
  return [...body.matchAll(/^ {2}(?:"([^"]+)"|([A-Za-z_$][\w$]*))\s*:/gm)].map(
    ([, quoted, bare]) => quoted ?? bare ?? '',
  );
}

// The module text, already in Prettier's format, so the test can compare it with the file.
export function renderCatalogModule(version: string, keys: readonly string[]): string {
  return [
    `// Generated by scripts/generate-functions.ts from fhirpath.js ${version}; do not edit.`,
    '// The keys of engine.invocationTable, operator entries included, because the engine accepts',
    '// them as names. Calling any other name throws "Not implemented: <name>".',
    'export const fhirPathFunctions: ReadonlySet<string> = new Set([',
    ...keys.map((key) => `  '${key}',`),
    ']);',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { version, source } = installedFhirPath();
  const keys = invocationTableKeys(source);
  writeFileSync(catalogModule, renderCatalogModule(version, keys));
  console.log(`Wrote ${String(keys.length)} fhirpath.js ${version} functions to ${catalogModule}`);
}
